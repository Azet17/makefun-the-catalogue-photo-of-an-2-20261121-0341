#!/usr/bin/env python3
"""Copy the shipped catalogue photo to the make.fun output directory.

Standard library only, no network. Expects entry.png next to this file
(it is generated by draw.py). Never deletes the output directory.
"""
import hashlib
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "entry.png")


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, "entry.png")
    shutil.copyfile(SRC, dst)
    src_hash = sha256(SRC)
    dst_hash = sha256(dst)
    if src_hash != dst_hash:
        print("ERROR: sha256 mismatch after copy", file=sys.stderr)
        return 1
    size = os.path.getsize(dst)
    print(f"copied entry.png -> {dst}")
    print(f"size: {size} bytes")
    print(f"sha256: {dst_hash}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
